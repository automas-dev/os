#define SYS_CALL_MEM_FREE    ((SYS_CALL_FAMILY_MEM << 16) | 0x0003)

#define SYS_CALL_PROC_EXIT           ((SYS_CALL_FAMILY_PROC << 16) | 0x0001)
#define SYS_CALL_PROC_ABORT          ((SYS_CALL_FAMILY_PROC << 16) | 0x0002)
#define SYS_CALL_PROC_PANIC          ((SYS_CALL_FAMILY_PROC << 16) | 0x0003)
#define SYS_CALL_PROC_REG_SIG        ((SYS_CALL_FAMILY_PROC << 16) | 0x0004)
#define SYS_CALL_PROC_GETPID         ((SYS_CALL_FAMILY_PROC << 16) | 0x0005)
#define SYS_CALL_PROC_QUEUE_EVENT    ((SYS_CALL_FAMILY_PROC << 16) | 0x0006)
#define SYS_CALL_PROC_YIELD          ((SYS_CALL_FAMILY_PROC << 16) | 0x0007)
#define SYS_CALL_PROC_EXEC           ((SYS_CALL_FAMILY_PROC << 16) | 0x0008)
#define SYS_CALL_PROC_SET_FOREGROUND ((SYS_CALL_FAMILY_PROC << 16) | 0x0009)
#define SYS_CALL_PROC_WAIT_PID       ((SYS_CALL_FAMILY_PROC << 16) | 0x000a)

#define SYS_CALL_PROC_LIST_OPEN
#define SYS_CALL_PROC_LIST_CLOSE
#define SYS_CALL_PROC_LIST_READ
#define SYS_CALL_PROC_LIST_

#define SYS_CALL_EVENT_PULL  ((SYS_CALL_FAMILY_EVENT << 16) | 0x0001)
#define SYS_CALL_EVENT_TIME  ((SYS_CALL_FAMILY_EVENT << 16) | 0x0002)
#define SYS_CALL_EVENT_SLEEP ((SYS_CALL_FAMILY_EVENT << 16) | 0x0003)

