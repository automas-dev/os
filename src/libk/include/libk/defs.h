#define SYS_CALL_FAMILY_IO      0x01
#define SYS_CALL_FAMILY_MEM     0x02
#define SYS_CALL_FAMILY_PROC    0x03
#define SYS_CALL_FAMILY_EVENT   0x04
#define SYS_CALL_FAMILY_STDIO   0x10
#define SYS_CALL_FAMILY_IO_FILE 0x11
#define SYS_CALL_FAMILY_IO_DIR  0x12
#define SYS_CALL_FAMILY_KERNEL  0x20

#define SYS_CALL_IO_OPEN  ((SYS_CALL_FAMILY_IO << 16) | 0x0001)
#define SYS_CALL_IO_CLOSE ((SYS_CALL_FAMILY_IO << 16) | 0x0002)
#define SYS_CALL_IO_READ  ((SYS_CALL_FAMILY_IO << 16) | 0x0003)
#define SYS_CALL_IO_WRITE ((SYS_CALL_FAMILY_IO << 16) | 0x0004)
#define SYS_CALL_IO_SIZE  ((SYS_CALL_FAMILY_IO << 16) | 0x0005)

#define SYS_CALL_MEM_MALLOC  ((SYS_CALL_FAMILY_MEM << 16) | 0x0001)
